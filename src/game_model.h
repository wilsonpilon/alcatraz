#pragma once

#include "msxgl.h"
#include "language.h"

typedef enum
{
	ITEM_SHEET,
	ITEM_STRIPS,
	ITEM_ROPE,
	ITEM_FOOD,
	ITEM_KEY,
	ITEM_COUNT
} GameItem;

enum
{
	ITEM_ABSENT,
	ROOM_CORRIDOR = 77,
	ROOM_GUARD = 78,
	ROOM_CELL = 79,
	ITEM_CARRIED = 255
};

typedef struct
{
	u8 room;
	u8 items[ITEM_COUNT];
	bool guard_gone;
	bool rope_cast;
	bool gate_open;
} GameState;

typedef enum
{
	RESULT_EMPTY,
	RESULT_LOOK,
	RESULT_INVENTORY,
	RESULT_WALL,
	RESULT_MOVED,
	RESULT_UNBUILT,
	RESULT_BARS_CLOSED,
	RESULT_TAKEN,
	RESULT_DROPPED,
	RESULT_ALREADY_CARRIED,
	RESULT_NOT_CARRIED,
	RESULT_NOT_VISIBLE,
	RESULT_FIXED_BED,
	RESULT_EXAMINE_BED,
	RESULT_EXAMINE_ITEM,
	RESULT_TORN,
	RESULT_TIED,
	RESULT_GUARD_LEFT,
	RESULT_NO_GUARD,
	RESULT_NO_BARS,
	RESULT_ROPE_TIED,
	RESULT_ROPE_HIT,
	RESULT_NOTHING,
	RESULT_KEY_FOUND,
	RESULT_GATE_OPEN,
	RESULT_GATE_ALREADY,
	RESULT_INPUT_FULL,
	RESULT_UNKNOWN
} GameResult;

void GameModel_Init(GameState* state);
GameResult GameModel_Command(GameState* state, Language language, const c8* input);
